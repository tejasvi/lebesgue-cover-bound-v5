PI = arb.pi()
def A(x): return arb(float(x)) if not isinstance(x, arb) else x
def Rn_arb(n): return 1/(2*(PI/(2*n)).cos())

# ---------------- definitions ----------------
def f_area(d):          # area of conv(D u {x}), |x| = d >= 1/2  (Lemma C)
    return (PI - (1/(2*d)).acos())/4 + (d*d - arb(1)/4).sqrt()/2
def g_corner(n, m):     # min over rotations of the max corner distance for centre at distance m (Lemma C)
    R = Rn_arb(n)
    return (R*R + m*m + 2*R*m*(PI/n).cos()).sqrt()

class Checker:
    def __init__(self, ns, tau, N, eps):
        self.ns = list(ns); self.k = len(ns); self.tau = arb(repr(float(tau))); self.N = N; self.eps = eps
        self.min_margin = None; self._leaf_margins = []
        self.dim = 2 + 3*(self.k - 1)
        # float corners for witness generation; arb corners for verification
        self.Vf = []; self.Va = []
        for n in ns:
            R = 1.0/(2*math.cos(math.pi/(2*n)))
            self.Vf.append(np.array([[R*math.cos(2*math.pi*l/n), R*math.sin(2*math.pi*l/n)] for l in range(n)]))
            Ra = Rn_arb(n)
            self.Va.append([(Ra*(2*PI*l/n).cos(), Ra*(2*PI*l/n).sin()) for l in range(n)])
        self.th = np.array([2*math.pi*j/N for j in range(N)])
    def pidx(self, i):
        if i == 1: return (None, 0, 1)
        b = 2 + 3*(i - 2); return (b, b + 1, b + 2)
    # ---------- float witness heuristic (independent implementation) ----------
    def _supp_body(self, i, rho, t, phis):
        """support value and point of body i (rotated by rho, translated by t) in directions phis (float)."""
        u = np.column_stack([np.cos(phis), np.sin(phis)])
        if i == 0: return np.full(len(phis), 0.5), 0.5*u
        n = self.ns[i-1]; c, s = math.cos(rho), math.sin(rho)
        V = self.Vf[i-1] @ np.array([[c, s], [-s, c]])         # rows rotated by rho
        proj = u @ V.T
        best = proj.max(axis=1); arg = proj.argmax(axis=1); pts = V[arg].copy()
        # arcs: the arc centred at corner l has outward normals in [phi_l + pi - pi/(2n), phi_l + pi + pi/(2n)]
        for l in range(n):
            phl = rho + 2*math.pi*l/n
            off = np.mod(phis - (phl + math.pi - math.pi/(2*n)), 2*math.pi)
            on = off <= math.pi/n
            val = 1.0 + proj[:, l]
            take = on & (val > best)
            best = np.where(take, val, best); pts = np.where(take[:, None], V[l] + u, pts)
        return best + u @ t, pts + t
    def _supp(self, pl, phis):
        hb = None
        for i in range(self.k + 1):
            rho, t = pl[i]
            h, P = self._supp_body(i, rho, t, phis)
            if hb is None: hb, Pb, ib = h, P, np.zeros(len(phis), dtype=int)
            else:
                m = h > hb; hb = np.where(m, h, hb); Pb = np.where(m[:, None], P, Pb); ib = np.where(m, i, ib)
        return ib, Pb, hb
    def placement(self, c):
        pl = [(0.0, np.zeros(2))]
        for i in range(1, self.k + 1):
            ir, ix, iy = self.pidx(i)
            pl.append((0.0 if ir is None else float(c[ir]), np.array([c[ix], c[iy]], dtype=float)))
        return pl
    def witnesses(self, c):
        pl = self.placement(c)
        ib, X, _ = self._supp(pl, self.th)
        keep = np.abs(X - np.roll(X, 1, axis=0)).max(axis=1) > 1e-14
        ib = list(ib[keep]); X = [x for x in X[keep]]
        for _ in range(60):
            P = np.array(X); Pn = np.roll(P, -1, axis=0); E = Pn - P
            nv = np.column_stack([E[:, 1], -E[:, 0]]); ln = np.hypot(nv[:, 0], nv[:, 1])
            idx = np.nonzero(ln > 1e-15)[0]
            phis = np.arctan2(nv[idx, 1], nv[idx, 0])
            jb, S, hs = self._supp(pl, phis)
            gap = hs - (P[idx]*(nv[idx]/ln[idx, None])).sum(axis=1)
            add = [(idx[m], int(jb[m]), S[m]) for m in range(len(idx)) if gap[m] > self.eps]
            if not add: break
            for (j, b, s) in sorted(add, key=lambda z: -z[0]):
                ib.insert(j + 1, b); X.insert(j + 1, s)
        Q = []
        for i, x in zip(ib, X):
            if i == 0: Q.append(np.array(x))
            else:
                rho, t = pl[i]; c_, s_ = math.cos(rho), math.sin(rho); y = np.array(x) - t
                Q.append(np.array([c_*y[0] + s_*y[1], -s_*y[0] + c_*y[1]]))
        return ib, Q
    # ---------- rigorous pieces ----------
    def box_arb(self, c, h):
        """placement intervals: for body i: (rho_c arb, rho_rad arb, t_c (arb,arb), t_rad arb (norm bound))."""
        out = [(arb(0), arb(0), (arb(0), arb(0)), arb(0))]
        for i in range(1, self.k + 1):
            ir, ix, iy = self.pidx(i)
            rc = arb(0) if ir is None else arb(float(c[ir])); rr = arb(0) if ir is None else arb(float(h[ir]))
            tc = (arb(float(c[ix])), arb(float(c[iy])))
            tr = (arb(float(h[ix]))**2 + arb(float(h[iy]))**2).sqrt()
            out.append((rc, rr, tc, tr))
        return out
    def member_ok(self, i, q):
        if i == 0: return q[0]*q[0] + q[1]*q[1] < arb(1)/4
        for (vx, vy) in self.Va[i-1]:
            dx = q[0] - vx; dy = q[1] - vy
            if not (dx*dx + dy*dy < 1): return False
        return True
    def check_bound_leaf(self, c, h):
        self._leaf_margins = []
        try:
            return self._check_bound_leaf_2level(c, h)
        finally:
            self._leaf_done()
    def _check_bound_leaf_2level(self, c, h):
        N0, e0 = self.N, self.eps
        self.N, self.eps = 256, 1e-5; self.th = np.array([2*math.pi*j/256 for j in range(256)])
        try:
            ok, msg = self._check_bound_leaf(c, h)
        finally:
            self.N, self.eps = N0, e0; self.th = np.array([2*math.pi*j/N0 for j in range(N0)])
        if ok: return ok, msg
        return self._check_bound_leaf(c, h)
    def _check_bound_leaf(self, c, h):
        res = self.verified_runs(c, h, c)
        if res[0] is None: return False, res[1]
        runs, pa = res
        return self.taylor_ok(runs, pa, h)
    def verified_runs(self, c, h, cprime):
        """witnesses from support points at cprime, verified (arb) to give a valid fan over the box (c, h)."""
        ib, Qf = self.witnesses(cprime)
        shrink = 1.0 - 2.0**-40
        Qf = [q*shrink for q in Qf]
        pa = self.box_arb(c, h)
        pl = self.placement(c)
        # float pre-screen of the fan with several centres and the drop rule (heuristic), then arb verification
        ZS = np.array([(0.0, 0.0)] + [(0.12*math.cos(a*math.pi/4), 0.12*math.sin(a*math.pi/4)) for a in range(8)])
        rho_b = np.array([pl[i][0] for i in range(self.k + 1)]); t_b = np.array([pl[i][1] for i in range(self.k + 1)])
        rr_b = np.zeros(self.k + 1); dt_b = np.zeros(self.k + 1)
        for i in range(1, self.k + 1):
            ir, ix, iy = self.pidx(i)
            rr_b[i] = 0.0 if ir is None else float(h[ir]); dt_b[i] = math.hypot(h[ix], h[iy])
        def lbs_f(ibv, Qv, z):
            ibv = np.asarray(ibv); Qv = np.asarray(Qv)
            cr, sr = np.cos(rho_b[ibv]), np.sin(rho_b[ibv])
            X = np.column_stack([cr*Qv[:, 0] - sr*Qv[:, 1], sr*Qv[:, 0] + cr*Qv[:, 1]]) + t_b[ibv] - z
            ib2 = np.roll(ibv, -1); Q2 = np.roll(Qv, -1, axis=0); X2 = np.roll(X, -1, axis=0)
            d0 = X[:, 0]*X2[:, 1] - X[:, 1]*X2[:, 0]
            same = ibv == ib2
            w = np.hypot(*(Q2 - Qv).T); tz = np.hypot(*(t_b[ibv] - z).T)
            vs = w*(dt_b[ibv]*(1 + rr_b[ibv]) + tz*rr_b[ibv])
            dX = np.hypot(*Qv.T)*rr_b[ibv] + dt_b[ibv]; dX2 = np.hypot(*Q2.T)*rr_b[ib2] + dt_b[ib2]
            vt = dX*(np.hypot(*X2.T) + dX2) + np.hypot(*X.T)*dX2
            return d0 - np.where(same, np.where(ibv == 0, 0.0, vs), vt)
        best = None
        for z in ZS:
            nb = int((lbs_f(ib, Qf, z) <= 1e-13).sum())
            if best is None or nb < best[0]: best = (nb, z)
            if nb == 0: break
        z = best[1]
        ib = list(ib); Qf = list(Qf)
        for _ in range(400):
            row = lbs_f(ib, Qf, z)
            bad = np.nonzero(row <= 1e-13)[0]
            n = len(ib)
            if len(bad) == 0 or n <= 4: break
            j = int(bad[0]); j2 = (j + 1) % n; drop = j2 if ib[j2] != 0 else j
            del ib[drop]; del Qf[drop]
        n = len(ib)
        if n < 3: return None, 'too few witnesses'
        # ---- arb verification ----
        Q = [(arb(float(q[0])), arb(float(q[1]))) for q in Qf]
        za = (arb(float(z[0])), arb(float(z[1])))
        if not (za[0]*za[0] + za[1]*za[1] < arb(1)/4): return None, 'fan centre outside disk'
        for i, q in zip(ib, Q):
            if not self.member_ok(i, q): return None, 'witness outside body'
        rot = {}
        for i in range(self.k + 1):
            rc = pa[i][0]; rot[i] = (rc.cos(), rc.sin())
        def placed(i, q):
            cs, sn = rot[i]; t = pa[i][2]
            return (cs*q[0] - sn*q[1] + t[0], sn*q[0] + cs*q[1] + t[1])
        def nrm(v): return (v[0]*v[0] + v[1]*v[1]).sqrt()
        Xc = [placed(i, q) for i, q in zip(ib, Q)]
        total_angle = arb(0)
        for j in range(n):
            j2 = (j + 1) % n; i, i2 = ib[j], ib[j2]
            x = (Xc[j][0] - za[0], Xc[j][1] - za[1]); y = (Xc[j2][0] - za[0], Xc[j2][1] - za[1])
            d0 = x[0]*y[1] - x[1]*y[0]
            if i == i2:
                if i == 0: var = arb(0)
                else:
                    rr, tr = pa[i][1], pa[i][3]
                    w = nrm((Q[j2][0] - Q[j][0], Q[j2][1] - Q[j][1]))
                    tz = nrm((pa[i][2][0] - za[0], pa[i][2][1] - za[1]))
                    var = w*(tr*(1 + rr) + tz*rr)
            else:
                dx = arb(0) if i == 0 else nrm(Q[j])*pa[i][1] + pa[i][3]
                dy = arb(0) if i2 == 0 else nrm(Q[j2])*pa[i2][1] + pa[i2][3]
                var = dx*(nrm(y) + dy) + nrm(x)*dy
            if not (d0 - var > 0): return None, f'fan order fails at {j}'
            total_angle += arb.atan2(d0, x[0]*y[0] + x[1]*y[1])
        if not (abs(total_angle - 2*PI) < 1): return None, 'winding'
        # ---- runs ----
        # rotate to start at a body change
        s0 = 0
        for j in range(n):
            if ib[j] != ib[j-1]: s0 = j; break
        ibr = ib[s0:] + ib[:s0]; Qr = Q[s0:] + Q[:s0]
        runs = []; j = 0
        while j < n:
            jj = j
            while jj + 1 < n and ibr[jj+1] == ibr[j]: jj += 1
            C = arb(0)
            for m in range(j, jj): C += Qr[m][0]*Qr[m+1][1] - Qr[m][1]*Qr[m+1][0]
            runs.append((ibr[j], Qr[j], Qr[jj], C)); j = jj + 1
        if os.environ.get('LBCHECK_SELFTEST'):
            Fd = arb(0)
            for jj in range(n):
                a_, b_ = Xc[jj], Xc[(jj + 1) % n]; Fd += (a_[0]*b_[1] - a_[1]*b_[0])/2
            self._Fdirect = Fd
        return runs, pa
    def taylor_ok(self, runs, pa, h):
        F, g, e = self.taylor_model(runs, pa, h)
        ha = [arb(float(x)) for x in h]
        L = F - e
        for k in range(self.dim): L -= abs(g[k])*ha[k]
        if os.environ.get('LBCHECK_SELFTEST') and hasattr(self, '_Fdirect'):
            assert abs(float((F - self._Fdirect).mid())) < 1e-12, ('F mismatch', F, self._Fdirect)
        self._margin(L)
        return (L > self.tau), f'L={L.str(12)}'
    def _margin(self, L):
        self._leaf_margins.append(float((L - self.tau).lower()))
    def _leaf_done(self):
        if self._leaf_margins:
            mg = max(self._leaf_margins)
            self.min_margin = mg if self.min_margin is None else min(self.min_margin, mg)
        self._leaf_margins = []
    def taylor_model(self, runs, pa, h):
        """returns F(c), grad F(c) (arb lists) and e >= sup_box of the second-order deficit (Lemma T)."""
        d = self.dim
        F = arb(0); g = [arb(0)]*d
        Hm = [[arb(0)]*d for _ in range(d)]; Wm = [[arb(0)]*d for _ in range(d)]
        def add(M, k, l, v):
            M[k][l] += v
            if k != l: M[l][k] += v
        def rotv(i, v):
            cs, sn = pa[i][0].cos(), pa[i][0].sin()
            return (cs*v[0] - sn*v[1], sn*v[0] + cs*v[1])
        def Jv(v): return (-v[1], v[0])
        def det(a, b): return a[0]*b[1] - a[1]*b[0]
        def nrm(v): return (v[0]*v[0] + v[1]*v[1]).sqrt()
        half = arb(1)/2
        nr = len(runs)
        for r in range(nr):
            i, qa, qb, C = runs[r]
            F += half*C
            if i != 0:
                ir, ix, iy = self.pidx(i)
                t = pa[i][2]; w = (qb[0] - qa[0], qb[1] - qa[1]); Rw = rotv(i, w); RJw = rotv(i, Jv(w))
                F += half*det(t, Rw)
                g[ix] += half*Rw[1]; g[iy] += -half*Rw[0]
                if ir is not None:
                    g[ir] += half*det(t, RJw)
                    add(Hm, ir, ir, -half*det(t, Rw)); add(Hm, ir, ix, half*RJw[1]); add(Hm, ir, iy, -half*RJw[0])
                    rr, tr = pa[i][1], pa[i][3]; nw = nrm(w); tn = nrm(t)
                    add(Wm, ir, ir, half*nw*(tr*(1 + rr) + tn*rr)); add(Wm, ir, ix, half*nw*rr); add(Wm, ir, iy, half*nw*rr)
            j, qn = runs[(r + 1) % nr][0], runs[(r + 1) % nr][1]
            x = rotv(i, qb) if i != 0 else qb
            if i != 0: x = (x[0] + pa[i][2][0], x[1] + pa[i][2][1])
            y = rotv(j, qn) if j != 0 else qn
            if j != 0: y = (y[0] + pa[j][2][0], y[1] + pa[j][2][1])
            F += half*det(x, y)
            dxs = {}; dys = {}
            if i != 0:
                ir, ix, iy = self.pidx(i); dxs[ix] = (arb(1), arb(0)); dxs[iy] = (arb(0), arb(1))
                if ir is not None: dxs[ir] = rotv(i, Jv(qb))
            if j != 0:
                jr, jx, jy = self.pidx(j); dys[jx] = (arb(1), arb(0)); dys[jy] = (arb(0), arb(1))
                if jr is not None: dys[jr] = rotv(j, Jv(qn))
            for k, v in dxs.items(): g[k] += half*det(v, y)
            for k, v in dys.items(): g[k] += half*det(x, v)
            for k, v in dxs.items():
                for l, v2 in dys.items(): add(Hm, k, l, half*det(v, v2))
            ra = arb(0) if i == 0 else pa[i][1]; ta = arb(0) if i == 0 else pa[i][3]
            rb = arb(0) if j == 0 else pa[j][1]; tb = arb(0) if j == 0 else pa[j][3]
            nqa = arb(0) if i == 0 else nrm(qb); nqb = arb(0) if j == 0 else nrm(qn)
            dxa = nqa*ra + ta; dyb = nqb*rb + tb
            if i != 0 and self.pidx(i)[0] is not None:
                ir = self.pidx(i)[0]
                add(Hm, ir, ir, half*det((-rotv(i, qb)[0], -rotv(i, qb)[1]), y))
                add(Wm, ir, ir, half*(nqa*ra*(nrm(y) + dyb) + nqa*dyb))
            if j != 0 and self.pidx(j)[0] is not None:
                jr = self.pidx(j)[0]
                add(Hm, jr, jr, half*det(x, (-rotv(j, qn)[0], -rotv(j, qn)[1])))
                add(Wm, jr, jr, half*(nqb*rb*(nrm(x) + dxa) + nqb*dxa))
            if i != 0 and j != 0 and self.pidx(i)[0] is not None and self.pidx(j)[0] is not None:
                add(Wm, self.pidx(i)[0], self.pidx(j)[0], half*nqa*nqb*(ra + rb))
            if i != 0 and self.pidx(i)[0] is not None and j != 0:
                ir = self.pidx(i)[0]; jr, jx, jy = self.pidx(j)
                add(Wm, ir, jx, half*nqa*ra); add(Wm, ir, jy, half*nqa*ra)
            if j != 0 and self.pidx(j)[0] is not None and i != 0:
                jr = self.pidx(j)[0]; ir, ix, iy = self.pidx(i)
                add(Wm, ix, jr, half*nqb*rb); add(Wm, iy, jr, half*nqb*rb)
        # lambda_min lower bound: float estimate, verified by arb LDL^T of H - lam I
        Hf = np.array([[float(Hm[a][b].mid()) for b in range(d)] for a in range(d)])
        lam_f = float(np.linalg.eigvalsh(0.5*(Hf + Hf.T))[0])
        lam = arb(min(0.0, lam_f) - 1e-9 - 1e-9*abs(lam_f))
        M = [[Hm[a][b] - (lam if a == b else 0) for b in range(d)] for a in range(d)]
        ok_psd = True
        Dg = []
        for a in range(d):
            for b in range(a):
                s = M[a][b]
                for k in range(b): s -= M[a][k]*M[b][k]*Dg[k]
                M[a][b] = s/Dg[b]
            s = M[a][a]
            for k in range(a): s -= M[a][k]*M[a][k]*Dg[k]
            if not (s > 0): ok_psd = False; break
            Dg.append(s)
        if not ok_psd:
            # Gershgorin fallback, in arb: lambda_min >= min_a (H_aa - sum_{b != a} |H_ab|); exact lower endpoints
            lam = arb(0)
            for a in range(d):
                r = Hm[a][a]
                for b in range(d):
                    if b != a: r = r - abs(Hm[a][b])
                rl = r.lower()
                if rl < lam: lam = rl
            self.n_gersh = getattr(self, 'n_gersh', 0) + 1
        ha = [arb(float(x)) for x in h]
        hh = sum((x*x for x in ha), arb(0))
        e = arb(0)
        if not (lam >= 0): e -= half*lam*hh
        for a in range(d):
            for b in range(d):
                e += half*Wm[a][b]*ha[a]*ha[b]
        return F, g, e
    def check_multi_leaf(self, c, h, shifts, lam):
        """Lemma K: for weights lam_i >= 0 normalised to sum 1 (in arb, so the exact normalised weights are used),
        min_box A >= sum_i lam_i (F_i(c) - e_i) - sum_k |sum_i lam_i g_ik| h_k, each F_i a fan verified on the box."""
        self._leaf_margins = []
        lam = [float(x) for x in lam]
        if any(not (x >= 0) for x in lam): return False, 'negative or NaN lambda'
        if not (sum(lam) > 0): return False, 'bad lambda'
        lam_a = [arb(x) for x in lam]; tot = sum(lam_a, arb(0)); lam_a = [x/tot for x in lam_a]
        Ls = arb(0); G = [arb(0)]*self.dim
        for sv, la, lf in zip(shifts, lam_a, lam):
            cp = c + np.asarray(sv, dtype=float)*h
            res = self.verified_runs(c, h, cp)
            if res[0] is None:
                if lf == 0.0: continue
                return False, 'structure invalid: ' + res[1]
            runs, pa = res
            F, g, e = self.taylor_model(runs, pa, h)
            Ls += la*(F - e)
            G = [G[k] + la*g[k] for k in range(self.dim)]
        ha = [arb(float(x)) for x in h]
        for k in range(self.dim): Ls -= abs(G[k])*ha[k]
        self._margin(Ls); self._leaf_done()
        return (Ls > self.tau), f'Lmulti={Ls.str(12)}'

    def check_far_leaf(self, lo, hi, T):
        for i in range(self.k):
            a, b = (0, 1) if i == 0 else (2 + 3*(i-1) + 1, 2 + 3*(i-1) + 2)
            mx = 0.0 if lo[a] <= 0 <= hi[a] else min(abs(lo[a]), abs(hi[a]))
            my = 0.0 if lo[b] <= 0 <= hi[b] else min(abs(lo[b]), abs(hi[b]))
            m = (arb(mx)**2 + arb(my)**2).sqrt()
            if m > 0:
                dd = g_corner(self.ns[i], m)
                if dd > arb(1)/2 and f_area(dd) > self.tau: return True
        return False

def check_root(meta):
    """root domain must contain every placement with area < tau (Lemmas R and C)."""
    ns = meta['ns']; tau = arb(repr(float(meta['tau']))); lo = meta['lo']; hi = meta['hi']
    errs = []
    for i, n in enumerate(ns):
        a, b = (0, 1) if i == 0 else (2 + 3*(i-1) + 1, 2 + 3*(i-1) + 2)
        w = min(-lo[a], hi[a], -lo[b], hi[b])
        if not (w > 0): errs.append(f'translation range of body {i+1} does not contain 0'); continue
        dd = g_corner(n, arb(w))
        if not (dd > arb(1)/2 and f_area(dd) > tau): errs.append(f'translation range of body {i+1} too small')
        if i >= 1:
            r = 2 + 3*(i-1)
            need = PI/n if i == 1 else 2*PI/n
            if not (lo[r] <= 0 and arb(hi[r]) >= need): errs.append(f'rotation range of body {i+1} too small')
    return errs

def check_part(certdir, part):
    okp, msgp = check_all_present(certdir)
    if not okp: return dict(part=part, ok=False, err='presence: ' + msgp)
    meta = json.load(open(os.path.join(certdir, f'part{part:04d}.json')))
    codes = np.load(os.path.join(certdir, f'part{part:04d}.npy'))
    errs = check_root(meta)
    if errs: return dict(part=part, ok=False, err='; '.join(errs))
    ch = Checker(meta['ns'], meta['tau'], meta['N'], meta['eps'])
    lo = np.array(meta['lo']); hi = np.array(meta['hi']); s0 = np.array(meta['split0'])
    cells = list(np.ndindex(*meta['split0']))[part::meta['nparts']]
    side = None
    mf = os.path.join(certdir, f'part{part:04d}_multi.npz')
    if os.path.exists(mf):
        z = np.load(mf); side = {}; off = 0
        zpos, zns, zsh, zlam = z['pos'], z['nstruct'], z['shifts'], z['lam']   # load each array once (v3)
        for pos_, ns_ in zip(zpos, zns):
            side[int(pos_)] = (zsh[off:off + ns_], zlam[off:off + ns_]); off += int(ns_)
    pos = 0; nleaf = 0; nfail = 0; fails = []
    def exact_box(l, h):
        """centre and half-widths of the leaf box [l, h] and whether c -+ w equals [l, h] exactly (rationals)."""
        c = 0.5*(l + h); w = 0.5*(h - l)
        ok = all(Fraction(float(c[k])) - Fraction(float(w[k])) == Fraction(float(l[k])) and
                 Fraction(float(c[k])) + Fraction(float(w[k])) == Fraction(float(h[k])) for k in range(len(l)))
        return ok, c, w
    for cell in cells:
        cl = lo + (hi - lo)*np.array(cell)/s0; chh = lo + (hi - lo)*(np.array(cell) + 1)/s0
        stack = [(cl, chh)]
        while stack:
            l, h = stack.pop()
            if pos >= len(codes): return dict(part=part, ok=False, err='certificate truncated')
            code = int(codes[pos]); pos += 1
            if code == 255:
                nleaf += 1
                if not ch.check_far_leaf(l, h, meta['T']): nfail += 1; fails.append(('far', l.tolist(), h.tolist()))
            elif code == 254:
                nleaf += 1
                okb, c_, w_ = exact_box(l, h)
                ok, msg = ch.check_bound_leaf(c_, w_) if okb else (False, 'leaf box not exactly c +- h')
                if not ok: nfail += 1; fails.append((msg, l.tolist(), h.tolist()))
            elif code == 253:
                nleaf += 1
                if side is None or (pos - 1) not in side:
                    nfail += 1; fails.append(('missing multi data', l.tolist(), h.tolist()))
                else:
                    shifts, lamv = side[pos - 1]
                    okb, c_, w_ = exact_box(l, h)
                    ok, msg = ch.check_multi_leaf(c_, w_, shifts, lamv) if okb else (False, 'leaf box not exactly c +- h')
                    if not ok: nfail += 1; fails.append((msg, l.tolist(), h.tolist()))
            elif 0 <= code < ch.dim:
                m = 0.5*(l[code] + h[code])
                l2, h2 = l.copy(), h.copy(); l2[code] = m
                l1, h1 = l.copy(), h.copy(); h1[code] = m
                stack.append((l2, h2)); stack.append((l1, h1))
            else:
                return dict(part=part, ok=False, err=f'bad code {code}')
    if pos != len(codes): return dict(part=part, ok=False, err='trailing data')
    if side is not None and set(side) - set(int(i) for i in np.nonzero(codes == 253)[0]):
        return dict(part=part, ok=False, err='multi data for a non-multi node')
    return dict(part=part, ok=(nfail == 0), leaves=nleaf, fails=nfail, min_margin=ch.min_margin, first_fails=fails[:3])

def check_all_present(certdir):
    metas = [json.load(open(os.path.join(certdir, f))) for f in sorted(os.listdir(certdir)) if f.startswith('part') and f.endswith('.json')]
    if not metas: return False, 'no parts'
    nparts = metas[0]['nparts']; keys = ('ns', 'tau', 'split0', 'lo', 'hi', 'nparts')
    if sorted(m['part'] for m in metas) != list(range(nparts)): return False, 'missing parts'
    for m in metas:
        if any(m[k] != metas[0][k] for k in keys): return False, 'inconsistent headers'
    return True, f"{nparts} parts, tau={metas[0]['tau']}, ns={metas[0]['ns']}"

